<?php

namespace App\Filament\Seller\Resources\Payments\Pages;

use App\Filament\Seller\Resources\Payments\PaymentResource;
use App\Helper\CheckFilamentSellerUser;
use App\Models\Currency;
use Filament\Resources\Pages\CreateRecord;

class CreatePayment extends CreateRecord
{
    protected static string $resource = PaymentResource::class;

    protected function mutateFormDataBeforeCreate(array $data): array
    {
        $data['seller_id'] = CheckFilamentSellerUser::getSellerId();
        $data['currency_id'] = Currency::where('code', 'MMK')->first()->id;

        return $data; // TODO: Change the autogenerated stub
    }
}
